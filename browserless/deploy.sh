#! /usr/bin/bash

set -e

source ./.env

# Timezone comes from the host, not this service.
if [ -z "${TZ:-}" ]; then
  TZ="$(tr -d '[:space:]' < /etc/timezone)"
fi

mkdir -p ${BROWSERLESS_DATA_PATH}
mkdir -p ${BROWSERLESS_DOWNLOADS_PATH}
mkdir -p ${BROWSERLESS_SCRATCH_PATH}
mkdir -p ${BROWSERLESS_METRICS_PATH}
mkdir -p ${BROWSERLESS_FONTS_PATH}
# The image runs as uid 999 and will not create these directories itself.
chmod -R 0777 ${BROWSERLESS_DATA_PATH}
chmod -R 0777 ${BROWSERLESS_DOWNLOADS_PATH}
chmod -R 0777 ${BROWSERLESS_SCRATCH_PATH}
chmod -R 0777 ${BROWSERLESS_METRICS_PATH}

export SERVICE_NAME=${SERVICE_NAME}
export BROWSERLESS_IMAGE=${BROWSERLESS_IMAGE}
export BROWSERLESS_PORT=${BROWSERLESS_PORT}
export BROWSERLESS_DATA_PATH=${BROWSERLESS_DATA_PATH}
export BROWSERLESS_DOWNLOADS_PATH=${BROWSERLESS_DOWNLOADS_PATH}
export BROWSERLESS_SCRATCH_PATH=${BROWSERLESS_SCRATCH_PATH}
export BROWSERLESS_METRICS_PATH=${BROWSERLESS_METRICS_PATH}
export BROWSERLESS_FONTS_PATH=${BROWSERLESS_FONTS_PATH}

export HOST=${HOST}
export PORT=${PORT}
export EXTERNAL=${EXTERNAL}
export TZ=${TZ}
export TOKEN=${TOKEN}
export STRICT_TOKEN_USE=${STRICT_TOKEN_USE}
export CONCURRENT=${CONCURRENT}
export QUEUED=${QUEUED}
export TIMEOUT=${TIMEOUT}
export RETRIES=${RETRIES}
export HEARTBEAT_INTERVAL=${HEARTBEAT_INTERVAL}
export DATA_DIR=${DATA_DIR}
export DOWNLOAD_DIR=${DOWNLOAD_DIR}
export SCRATCH_DIR=${SCRATCH_DIR}
export METRICS_JSON_PATH=${METRICS_JSON_PATH}
export CORS=${CORS}
export CORS_ALLOW_ORIGIN=${CORS_ALLOW_ORIGIN}
export CORS_ALLOW_METHODS=${CORS_ALLOW_METHODS}
export CORS_ALLOW_HEADERS=${CORS_ALLOW_HEADERS}
export CORS_ALLOW_CREDENTIALS=${CORS_ALLOW_CREDENTIALS}
export CORS_EXPOSE_HEADERS=${CORS_EXPOSE_HEADERS}
export CORS_MAX_AGE=${CORS_MAX_AGE}
export ALLOW_GET=${ALLOW_GET}
export ALLOW_FILE_PROTOCOL=${ALLOW_FILE_PROTOCOL}
export DISABLE_BLOCKLIST=${DISABLE_BLOCKLIST}
export MAX_PAYLOAD_SIZE=${MAX_PAYLOAD_SIZE}
export HEALTH=${HEALTH}
export MAX_CPU_PERCENT=${MAX_CPU_PERCENT}
export MAX_MEMORY_PERCENT=${MAX_MEMORY_PERCENT}
export MACHINE_STATS_SOURCE=${MACHINE_STATS_SOURCE}
export CPU_SAMPLE_INTERVAL_MS=${CPU_SAMPLE_INTERVAL_MS}
export CPU_EMA_ALPHA=${CPU_EMA_ALPHA}
export CPU_OVERLOAD_HYSTERESIS=${CPU_OVERLOAD_HYSTERESIS}
export DEBUG=${DEBUG}
export LOG_LEVEL=${LOG_LEVEL}
export LOG_FORMAT=${LOG_FORMAT}
export ENABLE_DEBUGGER=${ENABLE_DEBUGGER}
export OTEL_ENABLED=${OTEL_ENABLED}

DOCKER_COMPOSE=docker-compose.yml
DOCKER_COMPOSE_OUT="tmp-${DOCKER_COMPOSE}"

cat $DOCKER_COMPOSE | sed -e "s/{SERVICE_NAME}/${SERVICE_NAME}/g" > $DOCKER_COMPOSE_OUT

echo "[INFO] Pulling image (${BROWSERLESS_IMAGE}) from docker..."
docker pull "${BROWSERLESS_IMAGE}"

echo "[INFO] Deploying as stack..."
docker stack deploy --with-registry-auth \
  --resolve-image=always \
  --detach=true \
  --compose-file $DOCKER_COMPOSE_OUT common
